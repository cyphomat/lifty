const KEY = 'setlist.sprache';
export const SPRACHEN = ['de', 'en'];

export function sprache() {
  const s = localStorage.getItem(KEY);
  return SPRACHEN.includes(s) ? s : 'de';
}
export function setSprache(s) {
  if (SPRACHEN.includes(s)) localStorage.setItem(KEY, s);
}

