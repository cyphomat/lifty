/** Text zum Schluessel. Fehlt er auf Englisch, gilt der deutsche — eine
 *  luecke soll sichtbar deutsch sein, nicht als roher Schluessel auftauchen. */
export function t(key, vars) {
  const s = sprache();
  let txt = (TEXTE[s] && TEXTE[s][key]) ?? TEXTE.de[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) txt = txt.split(`{${k}}`).join(v);
  return txt;
}

/** Zahlformat der gewaehlten Sprache — 1.234 gegen 1,234. */
export function locale() { return t('locale'); }

/**
 * Feste Beschriftungen im HTML ersetzen. data-i18n setzt Text, data-i18n-html
 * erlaubt Auszeichnung im Text (Fettung, <code>), data-i18n-ph die Vorbelegung
 * von Eingabefeldern.
 */
export function uebersetzeStatisch(wurzel = document) {
  wurzel.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  wurzel.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  wurzel.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  wurzel.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  document.documentElement.lang = sprache();
}
